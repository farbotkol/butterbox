#!/usr/bin/env node
// Builds the reusable BB-BRAND-004 homepage imagery library from the
// repository-original Coastal Wave vector artwork. It never modifies the
// source SVG or the existing brand derivatives; it only (re)writes
// branding/website/homepage/.
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = "branding/auth/butterbox-coastal-artwork.svg";
const OUT_DIR = "branding/website/homepage";
const LOGO = "branding/logos/svg/butterbox-logo-horizontal-light.svg";

const art = readFileSync(join(root, SOURCE));
const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");

// Decorative by design: the artwork carries no information, so pages must use
// alt="" and keep the message in real text. The supporting tile includes the
// wordmark and therefore needs meaningful alternative text.
export const SETS = [
  {
    id: "hero-wide",
    use: "Homepage hero background, tablet and desktop (aspect 16:7)",
    ratio: [16, 7],
    widths: [640, 960, 1280, 1920, 2560],
    sizes: "100vw",
    alt: "",
    decorative: true,
  },
  {
    id: "hero-portrait",
    use: "Homepage hero background, phones (aspect 4:5, art direction via <picture> media)",
    ratio: [4, 5],
    widths: [480, 720, 960],
    sizes: "100vw",
    alt: "",
    decorative: true,
    // Keep the sun in frame when cropping the wide artwork to portrait.
    position: "southeast",
  },
  {
    id: "section-band",
    use: "Decorative divider above a footer or feature section (aspect 4:1)",
    ratio: [4, 1],
    widths: [800, 1600, 2400],
    sizes: "100vw",
    alt: "",
    decorative: true,
  },
  {
    id: "feature-tile",
    use: "Supporting marketing tile with the Butterbox wordmark (square)",
    ratio: [1, 1],
    widths: [480, 960],
    sizes: "(min-width: 768px) 33vw, 90vw",
    alt: "Butterbox logo above a calm coastal sunrise illustration",
    decorative: false,
    withLogo: true,
  },
];

async function tileSvg() {
  const logo = readFileSync(join(root, LOGO), "utf8");
  const [, , lw, lh] = logo.match(/viewBox="([^"]+)"/)[1].split(" ").map(Number);
  const inner = logo.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/<title>[\s\S]*?<\/title>/, "");
  const artInner = art.toString("utf8").replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  const scale = 700 / lw;
  return Buffer.from(
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 1000">` +
      `<rect width="1000" height="1000" fill="#FBF6EE"/>` +
      `<svg x="0" y="380" width="1000" height="620" viewBox="0 0 1200 560" preserveAspectRatio="xMaxYMax slice">${artInner}</svg>` +
      `<g transform="translate(${(1000 - lw * scale) / 2} ${150 - (lh * scale) / 2 + 40}) scale(${scale.toFixed(5)})">${inner}</g>` +
      `</svg>`,
  );
}

async function main() {
  const outDir = join(root, OUT_DIR);
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  const tile = await tileSvg();
  const files = [];
  for (const set of SETS) {
    const source = set.withLogo ? tile : art;
    for (const w of set.widths) {
      const h = Math.round((w * set.ratio[1]) / set.ratio[0]);
      const base = sharp(source, { density: Math.max(72, Math.ceil((w / 1000) * 96 * 1.5)) })
        .resize(w, h, { fit: "cover", position: set.position ?? "bottom" });
      for (const [fmt, opts] of [["avif", { quality: 55, effort: 6 }], ["webp", { quality: 80 }]]) {
        const name = `butterbox-coastal-${set.id}-${w}w.${fmt}`;
        const buf = await base.clone()[fmt](opts).toBuffer();
        writeFileSync(join(outDir, name), buf);
        files.push({ set: set.id, file: `${OUT_DIR}/${name}`, format: fmt, width: w, height: h, bytes: buf.length, sha256: sha256(buf) });
      }
    }
  }
  const manifest = {
    story: "BB-BRAND-004",
    status: "reusable library; no public homepage deployed",
    source: { file: SOURCE, sha256: sha256(art), provenance: "Original repository vector artwork generated by scripts/build-brand-assets.mjs (git 677a33e); not a photograph and not a product screenshot" },
    classification: "Illustration. Never present as photography or as an application screenshot.",
    sets: SETS.map(({ withLogo, ...s }) => ({ ...s, includesLogo: Boolean(withLogo) })),
    files,
  };
  writeFileSync(join(outDir, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
  writeFileSync(join(outDir, "preview.html"), previewHtml());
  console.log(JSON.stringify({ files: files.length, totalBytes: files.reduce((n, f) => n + f.bytes, 0) }));
}

function srcset(set, fmt) {
  return set.widths.map((w) => `butterbox-coastal-${set.id}-${w}w.${fmt} ${w}w`).join(", ");
}

function picture(set, { media } = {}) {
  const w = set.widths[1] ?? set.widths[0];
  const h = Math.round((w * set.ratio[1]) / set.ratio[0]);
  return `<picture>\n` +
    (media ? ["avif", "webp"].map((fmt) => `  <source media="(max-width: 599px)" type="image/${fmt}" srcset="${srcset(media, fmt)}" sizes="${media.sizes}" width="${media.widths[0]}" height="${Math.round((media.widths[0] * media.ratio[1]) / media.ratio[0])}">\n`).join("") : "") +
    `  <source type="image/avif" srcset="${srcset(set, "avif")}" sizes="${set.sizes}">\n` +
    `  <img src="butterbox-coastal-${set.id}-${w}w.webp" srcset="${srcset(set, "webp")}" sizes="${set.sizes}" width="${w}" height="${h}" alt="${set.alt}" ${set.id.startsWith("hero") ? 'fetchpriority="high"' : 'loading="lazy"'} decoding="async">\n</picture>`;
}

function previewHtml() {
  const [wide, portrait, band, tile] = SETS;
  return `<!doctype html>
<html lang="en-AU">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Butterbox homepage imagery preview (internal, not deployed)</title>
<style>
  body { margin: 0; font-family: system-ui, sans-serif; color: #26343A; background: #FBF6EE; }
  .hero { position: relative; }
  .hero img { display: block; width: 100%; height: auto; }
  .hero .copy { position: absolute; inset: 0; padding: 6vw; max-width: 34rem; }
  /* Phones: stack the copy above the art so text never sits on the sun. */
  @media (max-width: 599px) { .hero { display: flex; flex-direction: column-reverse; } .hero .copy { position: static; padding: 1.5rem; } }
  h1 { font-size: clamp(1.6rem, 4vw, 3rem); margin: 0 0 .5rem; }
  .note { background: #fff; border-left: 4px solid #2F7F86; padding: 1rem; margin: 1.5rem; }
  .grid { display: grid; gap: 1.5rem; padding: 1.5rem; grid-template-columns: repeat(auto-fit, minmax(16rem, 1fr)); align-items: start; }
  .grid img { display: block; width: 100%; max-width: 30rem; height: auto; }
  .band img { display: block; width: 100%; height: auto; }
</style>
</head>
<body>
<main>
<section class="hero" aria-labelledby="hero-title">
${picture(wide, { media: portrait })}
  <div class="copy"><h1 id="hero-title">Rosters, attendance and payroll prep for hospitality teams</h1>
  <p>Internal imagery preview for BB-BRAND-004. Illustration only — not a photograph or product screenshot.</p></div>
</section>
<p class="note">Decorative images use empty alt text; the message is carried by the real heading. This page is a verification harness and is not a deployed homepage.</p>
<div class="grid">
${picture(tile)}
<p>The supporting tile contains the Butterbox wordmark, so it has meaningful alternative text.</p>
</div>
<div class="band">
${picture(band)}
</div>
</main>
</body>
</html>
`;
}

await main();
